/**
 * Канон мира портфеля: одно «сейчас», одни форматы, одни правила про людей.
 *
 * Модели концептов (concepts/<slug>/model.mjs) строят даты и числа отсюда,
 * поэтому день недели не расходится с датой, а время, расстояние и деньги
 * записаны одинаково во всех 46 концептах.
 *
 * Правила, которые код не проверит, но модель обязана соблюдать:
 * - Статус-бар всегда 9:41 (конвенция Apple), с контентом его не сверяют.
 *   «Сейчас» в продукте — одно на концепт: moment(дата, время). События до него
 *   уже случились, после — впереди; «сегодня», «вчера», «через 6 дней» считаются от него.
 * - Люди вымышленные, с русскими именами и фамилиями; знаменитостей и брендов-людей нет.
 *   Фото назначено человеку, а не экрану: один человек — один кадр во всём концепте.
 *   Пользователь — один из людей модели с пометкой «это вы».
 * - Места могут быть реальными общественными (парк, двор, рынок), адреса и номера квартир — вымышленные.
 * - Тестовый телефон один на портфель: +7 900 123-45-67.
 */

export const YEAR = 2026;
export const STATUS_TIME = '9:41';
export const TEST_PHONE = '+7 900 123-45-67';

const WEEKDAYS = ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'];
const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'];

const parse = (iso) => { const [y, m, d] = iso.split('-').map(Number); return new Date(Date.UTC(y, m - 1, d)); };

/** «суббота, 23 мая» — день недели всегда сходится с датой. */
export const dayLabel = (iso) => { const d = parse(iso); return `${WEEKDAYS[d.getUTCDay()]}, ${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]}`; };
/** «23 мая» */
export const dateLabel = (iso) => { const d = parse(iso); return `${d.getUTCDate()} ${MONTHS[d.getUTCMonth()]}`; };
/** «сб», «вс» — для коротких меток и списков */
export const weekdayShort = (iso) => ['вс', 'пн', 'вт', 'ср', 'чт', 'пт', 'сб'][parse(iso).getUTCDay()];
/** Сдвиг даты на n дней: «завтра», «через неделю» считаются от сегодняшнего дня модели */
export const addDays = (iso, n) => { const d = parse(iso); d.setUTCDate(d.getUTCDate() + n); return d.toISOString().slice(0, 10); };

/** «Сейчас» концепта: дата и время модели (по умолчанию 9:41, как статус-бар). */
export const moment = (iso, time = STATUS_TIME) => ({ iso, date: dayLabel(iso), short: dateLabel(iso), time });

/* Форматы: тонкостей нет, правила одни на портфель */
/** Интервал времени с короткой чертой: «9:30–15:00» */
export const range = (from, to) => `${from}–${to}`;
/** Расстояние: «240 м», «2,4 км» */
export const distance = (meters) => (meters < 1000 ? `${meters} м` : `${(meters / 1000).toFixed(1).replace('.', ',').replace(/,0$/, '')} км`);
/** Деньги: «12 400 ₽» с неразрывным пробелом в разрядах */
export const rub = (n) => `${String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ₽`;
/** Количество с правильной формой: plural(3, 'вещь', 'вещи', 'вещей') → «3 вещи» */
export const plural = (n, one, few, many) => {
  const t = n % 100, u = n % 10;
  return `${n} ${t >= 11 && t <= 14 ? many : u === 1 ? one : u >= 2 && u <= 4 ? few : many}`;
};
/** Дней от a до b: «осталось 14 дней» считается, а не пишется руками */
export const daysBetween = (a, b) => Math.round((parse(b) - parse(a)) / 86400000);
